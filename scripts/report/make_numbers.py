"""Write paper/v2/numbers.tex for the legacy report: one LaTeX macro per result number.

The legacy report uses these macros. The current manuscript tables are generated by
manuscript/build_tables.py.
Each macro line carries a comment naming the file and the field it came from.

Sources:
  Study 3 core      results/part3/final/analysis.json
  Study 3 addendum  results/part3/addendum/analysis.json   (pre-registered after the core results)
  Study 3 explore   results/part3/explore_long/            (via scripts/part3/explore_long_report.py)
  Study 2           results/part2/final/analysis/confirmatory.json
  Study 1           results/part1/final/comparison.json

Run:  python3 scripts/report/make_numbers.py [--out paper/v2/numbers.tex] [--require-addendum]
Without the addendum results its macros print a visible "[pending]" so a draft still builds.
"""
from __future__ import annotations

import argparse
import json
import math
import statistics as S
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "part3"))

CORE = ROOT / "results/part3/final/analysis.json"
ADD = ROOT / "results/part3/addendum/analysis.json"
LONG = ROOT / "results/part3/explore_long"
P2 = ROOT / "results/part2/final/analysis/confirmatory.json"
P1 = ROOT / "results/part1/final/comparison.json"
OUT = ROOT / "paper/v2/numbers.tex"

METHOD = {"oe": "Oe", "oe_fixed": "OeFixed", "ppo_fixed": "PpoFixed", "ppo_dr": "PpoDr",
          "es_dr": "EsDr", "es_fixed": "EsFixed"}
WORD = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten"]
PENDING = r"\textbf{[pending]}"


def word(n: int) -> str:
    return WORD[n]


def esc(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"),
                 ("_", r"\_"), ("$", r"\$"), ("{", r"\{"), ("}", r"\}"), ("~", r"\~{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def num(x: float, d: int = 3, sign: bool = False) -> str:
    """A number for text or maths: fixed decimals, a true minus sign."""
    if x is None or (isinstance(x, float) and math.isnan(x)):
        raise ValueError("missing number")
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    # "-0.000" is kept, as the reports print it: it shows the value is below 0 (e.g. a CI end)
    return r"\ensuremath{" + s + "}"


def pval(p: float) -> str:
    """p-values as the generated reports print them: 4 significant digits; below 1e-4 in powers of 10."""
    if p >= 1e-4:
        return r"\ensuremath{" + f"{p:.4g}" + "}"
    m, e = f"{p:.3e}".split("e")
    return r"\ensuremath{" + f"{m}\\times 10^{{{int(e)}}}" + "}"


class Macros:
    def __init__(self):
        self.lines: list[tuple[str, str, str]] = []
        self.names: set[str] = set()

    def add(self, name: str, value: str, source: str):
        if not name.isalpha():
            raise ValueError(f"macro name must be letters only: {name}")
        if name in self.names:
            raise ValueError(f"macro defined twice: {name}")
        self.names.add(name)
        self.lines.append((name, value, source))

    def text(self) -> str:
        out = ["% Generated by scripts/report/make_numbers.py. Do not edit by hand.", ""]
        for name, value, source in self.lines:
            out.append(f"\\newcommand{{\\{name}}}{{{value}}}% {source}")
        return "\n".join(out) + "\n"


def ci3(m: Macros, base: str, value: float, ci, src: str, d: int = 3):
    m.add(base, num(value, d), src)
    m.add(base + "Lo", num(ci[0], d), src + " ci[0]")
    m.add(base + "Hi", num(ci[1], d), src + " ci[1]")


def comparison_rows(m: Macros, prefix: str, rows: list[dict], src: str):
    """Secondary or addendum family rows (same record shape: see analysis.compare_family)."""
    for r in rows:
        tag = prefix + word(int(r["name"][1:]))
        s = f"{src} {r['name']}"
        ci3(m, tag + "Diff", r["iqm_difference"], r["ci"], s + " iqm_difference")
        m.add(tag + "PXgtY", num(r["p_x_greater"], 3), s + " p_x_greater")
        m.add(tag + "P", pval(r["p"]), s + " p")
        m.add(tag + "PHolm", pval(r["p_holm"]), s + " p_holm")
        m.add(tag + "Result", esc(r["result"]), s + " result")


def study3_core(m: Macros):
    d = json.loads(CORE.read_text())
    src = "results/part3/final/analysis.json"
    h1 = d["h1"]
    ci3(m, "HOneD", h1["D"], h1["ci"], f"{src} h1.D")
    m.add("HOneMargin", num(h1["margin"], 2), f"{src} h1.margin")
    m.add("HOneVerdict", esc(h1["verdict"]), f"{src} h1.verdict")
    m.add("HOnePOeGreater", num(h1["p_oe_greater"], 3), f"{src} h1.p_oe_greater")
    m.add("BootReps", f"{d['bootstrap_reps']:,}".replace(",", "{,}"), f"{src} bootstrap_reps")
    m.add("BootSeed", str(h1["seed"]), f"{src} h1.seed")
    for k, (v, lo, hi) in d["iqm_primary"].items():
        ci3(m, "IQM" + METHOD[k], v, (lo, hi), f"{src} iqm_primary.{k}")
    comparison_rows(m, "Sec", d["secondary"], src + " secondary")
    h = d["h2b"]
    for k, nm in (("variety", "Variety"), ("method", "Method"), ("delta", "Delta"), ("interaction", "Interaction")):
        ci3(m, "HTwoB" + nm, h[k]["value"], h[k]["ci"], f"{src} h2b.{k}")
    m.add("HTwoBVerdict", esc(h["verdict"]), f"{src} h2b.verdict")
    m.add("RunsPerMethod", str(len(d["per_run"]["oe"])), f"{src} per_run.oe (count)")
    m.add("ExcludedRuns", str(len(d["excluded_runs"])), f"{src} excluded_runs (count)")
    m.add("EnvsLeftOut", str(len(d["environments_left_out"])), f"{src} environments_left_out (count)")
    for k, c in d["compute"].items():
        tag = METHOD[k]
        m.add("TrainWallMin" + tag, num(c["train_wall_hours_mean"] * 60, 1), f"{src} compute.{k}.train_wall_hours_mean x60")
        m.add("AdaptWallMin" + tag, num(c["adapt_wall_hours_mean"] * 60, 1), f"{src} compute.{k}.adapt_wall_hours_mean x60")
    m.add("CoreCost", num(d["cost"]["total"], 2), f"{src} cost.total")
    m.add("CoreMachineHours", num(d["cost"]["machine_hours"], 1), f"{src} cost.machine_hours")
    m.add("GpuPricePerHour", num(d["cost"]["price_per_hour"], 2), f"{src} cost.price_per_hour")


def study3_addendum(m: Macros, require: bool):
    src = "results/part3/addendum/analysis.json"
    names = ["AOneD", "AOneDLo", "AOneDHi", "AOneVerdict", "AOnePEsDrGreater",
             "IQMEsFixed", "IQMEsFixedLo", "IQMEsFixedHi",
             "AFourVarietyEs", "AFourVarietyEsLo", "AFourVarietyEsHi",
             "AFourVarietyOe", "AFourVarietyOeLo", "AFourVarietyOeHi",
             "AFourInteraction", "AFourInteractionLo", "AFourInteractionHi", "AFourVerdict",
             "AddRerunFlag", "AddSpend"]
    for i in (2, 3):
        names += [f"Add{word(i)}{x}" for x in ("Diff", "DiffLo", "DiffHi", "PXgtY", "P", "PHolm", "Result")]
    if not ADD.exists():
        if require:
            raise SystemExit(f"{ADD} not found (--require-addendum)")
        for n in names:
            m.add(n, PENDING, f"{src} not yet written")
        return
    d = json.loads(ADD.read_text())
    if not d.get("verdicts_given"):
        raise SystemExit("addendum: verdicts not given (more than 2 seeds left out); write these numbers by hand-checked text")
    a1 = d["a1"]
    ci3(m, "AOneD", a1["D"], a1["ci"], f"{src} a1.D")
    m.add("AOneVerdict", esc(a1["verdict"]), f"{src} a1.verdict")
    m.add("AOnePEsDrGreater", num(a1["p_es_dr_greater"], 3), f"{src} a1.p_es_dr_greater")
    v, lo, hi = d["iqm_primary"]["es_fixed"]
    ci3(m, "IQMEsFixed", v, (lo, hi), f"{src} iqm_primary.es_fixed")
    comparison_rows(m, "Add", d["family"], src + " family")
    a4 = d["a4"]
    for k, nm in (("variety_es", "VarietyEs"), ("variety_oe", "VarietyOe"), ("interaction", "Interaction")):
        ci3(m, "AFour" + nm, a4[k]["value"], a4[k]["ci"], f"{src} a4.{k}")
    m.add("AFourVerdict", esc(a4["verdict"]), f"{src} a4.verdict")
    m.add("AddRerunFlag", "yes" if d["es_dr_check"]["flag"] else "no", f"{src} es_dr_check.flag")
    spend = d.get("spend") or {}
    m.add("AddSpend", num(spend["total"], 2) if "total" in spend else PENDING, f"{src} spend.total")


def study3_long(m: Macros):
    import explore_long_report as L
    src = "results/part3/explore_long/oe_seed*/curves.json via explore_long_report.gain"
    gains = [L.gain([p["score"] for p in L.curve(LONG / f"oe_seed{s}")]) for s in L.SEEDS]
    for s, g in zip(L.SEEDS, gains):
        m.add("LongGain" + word(L.SEEDS.index(s) + 1), num(g, 2, sign=True), f"{src} seed {s}")
    m.add("LongReading", esc(L.reading(gains)), f"{src} reading")
    m.add("LongGainClear", num(L.GAIN_CLEAR, 1), "scripts/part3/explore_long_report.py GAIN_CLEAR")
    sp = json.loads((LONG / "spend.json").read_text())
    m.add("LongSpend", num(sp["total"], 2), "results/part3/explore_long/spend.json total")


def study2(m: Macros):
    d = json.loads(P2.read_text())["main"]
    src = "results/part2/final/analysis/confirmatory.json main"
    for row, rec in d["raw"].items():
        tag = "PTwoRow" + word(int(row))
        for meas, d_ in (("P1", 2), ("P2", 2)):
            r = rec[meas]
            ci3(m, tag + meas.replace("1", "One").replace("2", "Two"), r["diff"], r["ci95"],
                f"{src}.raw.{row}.{meas}.diff", d_)
        dec = d["decided"][row]
        m.add(tag + "Overall", esc(dec["overall_label"]), f"{src}.decided.{row}.overall_label")


def study1(m: Macros):
    d = json.loads(P1.read_text())
    src = "results/part1/final/comparison.json"
    assert d["n_runs"]["ET"] == d["n_runs"]["GS"], "group sizes differ; report separately"
    m.add("POneRuns", str(d["n_runs"]["ET"]), f"{src} n_runs.ET (equals GS)")


def build(out: Path, require_addendum: bool) -> Macros:
    m = Macros()
    study3_core(m)
    study3_addendum(m, require_addendum)
    study3_long(m)
    study2(m)
    study1(m)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(m.text())
    return m


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--require-addendum", action="store_true")
    a = ap.parse_args()
    m = build(Path(a.out), a.require_addendum)
    print(f"{len(m.lines)} macros written to {a.out}")

