"""The tuning results, generated from results/part3/tuning (PREREG Section 5).

  venv3/bin/python scripts/part3/report_tuning.py      # writes docs/TUNING_part3.md
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TUNING = ROOT / "results/part3/tuning"
NAMES = {"oe": "OE", "oe_fixed": "OE-fixed", "ppo_fixed": "PPO-fixed", "ppo_dr": "PPO-DR", "es_dr": "ES-DR"}


def fmt(v):
    return f"{v:.3g}" if isinstance(v, float) else str(v)


def main():
    spend = json.loads((TUNING / "spend.json").read_text())
    out = ["# Part 3 tuning results\n",
           "Generated by `scripts/part3/report_tuning.py` from `results/part3/tuning/` (one summary per method, "
           "`tuning_<method>.json`, plus each trial's run folder and every machine's logs). Protocol: PREREG Section 5. The chosen settings are in "
           "`configs/part3/tuned.yaml`, written by `tune.py --write-tuned`.\n",
           "Each trial trained for 5 × 10⁷ agent-steps (a quarter of the final budget) and was scored on the 24 "
           "validation environments only: mean of (competence − random-policy competence), zero-shot, 8 episodes. "
           "The highest score was chosen; ties go to the lower trial number. One trial per setting, so a score "
           "mixes the setting's effect with run-to-run luck.\n"]
    for m in NAMES:
        s = json.loads((TUNING / f"tuning_{m}.json").read_text())
        keys = sorted(s["trials"][0]["settings"])
        out.append(f"## {NAMES[m]}\n")
        out.append(f"Commit {s['git']['commit'][:7]} (clean: {s['git']['clean']}); hardware: "
                   f"{'; '.join(s['hardware'].get('gpus', []))}.\n")
        out.append("| Trial | seed | " + " | ".join(keys) + " | score | chosen |")
        out.append("|---|---|" + "---|" * len(keys) + "---|---|")
        for t in s["trials"]:
            sc = "failed" if t.get("failed") else f"{t['score']:.3f}"
            out.append(f"| {t['trial']} | {t['seed']} | " + " | ".join(fmt(t["settings"][k]) for k in keys)
                       + f" | {sc} | {'yes' if t['trial'] == s['chosen']['trial'] else ''} |")
        out.append("")
    out.append("## Compute cost\n")
    out.append("| Part | Machine hours | Storage hours | Cost |")
    out.append("|---|---|---|---|")
    for part, r in spend["parts"].items():
        out.append(f"| {part} | {r['pod_hours']:.2f} | {r['volume_hours']:.2f} | ${r['cost']:.2f} |")
    out.append(f"\nTotal stage cost: **${spend['total']:.2f}** (prespecified cap: $8).\n")
    (ROOT / "docs/TUNING_part3.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
